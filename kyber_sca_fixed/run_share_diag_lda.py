"""
Mask-aware profiling diagnostic with a template attack: can an attacker who knows the masks during profiling
recover HW of share 0 of coefficient 0 from a single trace? This isolates what shuffling/dummies hide
(the share sits at a fixed sample in C1 but at a random, jittered position in C2).
"""
import json, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sim, metrics, attack

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
SEED, N_TRAIN, N_TEST = 11, 6000, 2000


def main():
    ss = np.random.SeedSequence(SEED)
    rows = []
    for sigma in (0.1, 0.5):
        for mode in ("C1", "C2"):
            rng = np.random.default_rng(ss.spawn(1)[0])
            s_tr = sim.sample_secret(rng, N_TRAIN); Xtr, atr = sim.gen_traces(mode, s_tr, rng, sigma)
            s_te = sim.sample_secret(rng, N_TEST);  Xte, ate = sim.gen_traces(mode, s_te, rng, sigma)
            y_tr, y_te = atr["share0_hw0"], ate["share0_hw0"]
            ta = attack.TemplateAttack(k=10).fit(Xtr, y_tr)
            pred = ta.log_probs(Xte).argmax(1)
            k = int((pred == y_te).sum())
            lo, hi = metrics.binom_ci(k, N_TEST)
            snr, _ = metrics.snr_nicv(Xtr, y_tr)
            rows.append({"mode": mode, "sigma": sigma, "top1": k / N_TEST, "ci95": [lo, hi],
                         "majority": float(np.bincount(y_te).max() / N_TEST),
                         "peak_snr": float(snr.max()), "peak_sample": int(snr.argmax())})
            print(rows[-1], flush=True)
    json.dump({"seed": SEED, "rows": rows}, open(os.path.join(OUT, "share_diag_lda.json"), "w"), indent=1)
    NAME = {"C1": "C1 (masked)", "C2": "C2 (hybrid)"}
    L = [r"% AUTO-GENERATED by run_share_diag_lda.py -- measured values only",
         r"\begin{table}[t]\centering",
         r"\caption{Mask-aware profiling diagnostic: a template attack (top-10 SNR samples, LDA), profiled with known masks, predicts $\mathrm{HW}$ of share $s_0$ of coefficient 0 from a single trace "
         rf"({N_TRAIN} profiling / {N_TEST} test traces, random keys and masks). The share sits at a fixed sample in C1 and at a random, jittered position in C2.}}",
         r"\label{tab:sharediag}\begin{tabular}{llrrrr}\toprule",
         r"Config. & $\sigma$ & Top-1 (\%) & 95\% CI & Majority (\%) & Peak SNR\\\midrule"]
    for r in rows:
        L.append(rf"{NAME[r['mode']]} & {r['sigma']} & {100 * r['top1']:.1f} & {100 * r['ci95'][0]:.1f}--{100 * r['ci95'][1]:.1f} & {100 * r['majority']:.1f} & {r['peak_snr']:.4f}\\")
    L.append(r"\bottomrule\end{tabular}\end{table}")
    open(os.path.join(OUT, "tables_sharediag.tex"), "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
