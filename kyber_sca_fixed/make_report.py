"""Turn results/*.json|npz into figures and LaTeX tables with MEASURED values only."""
import json, os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
tv = json.load(open(os.path.join(R, "tvla.json")))
nc = json.load(open(os.path.join(R, "null_calibration.json")))
at = json.load(open(os.path.join(R, "attacks.json")))
cv = np.load(os.path.join(R, "attack_curves_rescored.npz"))     # calibrated-MAP curves (see rescore.py)
resc = json.load(open(os.path.join(R, "attacks_rescored.json")))
for _k, _e in at["results"].items():
    for _m in _e["models"]:
        _r = resc[f"{_k}|{_m['arch']}"]
        _m["ge_raw_trainprior"] = _m["ge_at_nmax"]
        _m.update({"ge_at_nmax": _r["ge_at_nmax"], "sr_at_nmax": _r["sr_at_nmax"], "traces_for_sr90": _r["traces_for_sr90"],
                   "traces_for_sr50": _r["traces_for_sr50"]})
tvc = np.load(os.path.join(R, "tvla_curves.npz"))
MODES = ["C0", "C1", "C2"]
NAME = {"C0": "C0 (unmasked)", "C1": "C1 (masked)", "C2": "C2 (hybrid)"}
PRIOR_GE = 1.2   # overwritten from data below
ARCH = {"lda": "Template (LDA)", "mlp": "MLP", "cnn": "CNN", "transformer": "Transformer"}
thr = tv["t_threshold"]
PRIOR_GE = float(np.mean([m["prior_only_rank"] for e in at["results"].values() for m in e["models"]]))


# ---------------- TVLA figure + table ----------------
def tvla_fig(sigma):
    fig, ax = plt.subplots(2, 3, figsize=(11, 5), sharex=True)
    for j, m in enumerate(MODES):
        for i, o in enumerate((1, 2)):
            t = tvc[f"t{o}_{m}_{sigma}"]
            ax[i, j].plot(np.abs(t), lw=0.6, color="#1f4e79")
            ax[i, j].axhline(thr, color="#c0392b", ls="--", lw=1)
            ax[i, j].set_title(f"{NAME[m]} - order {o}", fontsize=9)
            ax[i, j].set_ylim(0, max(6, np.abs(t).max() * 1.05)) if np.abs(t).max() < 30 else ax[i, j].set_yscale("log")
            if j == 0: ax[i, j].set_ylabel("|t|")
            if i == 1: ax[i, j].set_xlabel("sample index")
    fig.suptitle(f"TVLA fixed-vs-random secret, N={tv['n_per_class']}/class, sigma={sigma} (dashed: |t|=4.5)", fontsize=10)
    fig.tight_layout(); fig.savefig(os.path.join(R, f"fig_tvla_sigma{sigma}.png"), dpi=160); plt.close(fig)


for s in tv["sigmas"]:
    tvla_fig(s)


def tvla_rows(sigma):
    rows = []
    for m in MODES:
        for o in (1, 2):
            rs = [r for r in tv["results"] if r["sigma"] == sigma and r["mode"] == m]
            mx = [r[f"order{o}"]["max_abs_t"] for r in rs]
            nl = [r[f"order{o}"]["n_leaking"] for r in rs]
            ex = sum(v > thr for v in mx)
            verdict = "Yes" if ex == len(rs) else ("No" if ex == 0 else f"Inconclusive ({ex}/{len(rs)} keys)")
            rows.append((m, o, min(mx), max(mx), min(nl), max(nl), verdict))
    return rows


def f(v): return f"{v:.2f}"


L = []
L.append("% AUTO-GENERATED by make_report.py -- measured values only")
for s in tv["sigmas"]:
    L.append(r"\begin{table}[t]\centering")
    L.append(rf"\caption{{TVLA fixed-vs-random secret key, $N={tv['n_per_class']}$ traces per class, $\sigma={s}$, threshold $|t|>4.5$. "
             rf"Range over {tv['n_fixed_keys']} different fixed secrets. A configuration is marked as leaking only if the threshold is exceeded for every fixed secret.}}")
    L.append(rf"\label{{tab:tvla_s{str(s).replace('.', '')}}}")
    L.append(r"\begin{tabular}{llrrl}\toprule")
    L.append(r"Config. & Order & Max $|t|$ (min--max) & Leaking samples (min--max) & Leakage\\\midrule")
    for m, o, a, b, na, nb, v in tvla_rows(s):
        L.append(rf"{m} & {o} & {f(a)}--{f(b)} & {na}--{nb} & {v}\\")
    L.append(r"\bottomrule\end{tabular}\end{table}")
L.append("")
tot = sum(r["reps"] * 2 for r in nc["rows"]); fa = sum(r["o1_false_alarms"] + r["o2_false_alarms"] for r in nc["rows"])
L.append(rf"% Null calibration: {fa} false alarms in {tot} fixed-vs-fixed statistics ({100 * fa / tot:.2f}\%).")

LT = L[:]; L = []
# ---------------- attacks table ----------------
def attack_rows(sigma):
    rows = []
    for m in MODES:
        e = at["results"][f"{m}@{sigma}"]
        for r in e["models"]:
            rows.append((m, r, e))
    return rows


for s in sorted({p[0] for p in at["plan"]}, reverse=True):
    L.append(r"\begin{table}[t]\centering")
    L.append(rf"\caption{{Profiled attacks on $\mathrm{{HW}}(s[0][0])$, $\sigma={s}$. Profiling on {at['n_train']} random-key traces, test on {at['n_test']} random-key traces. "
             rf"GE/SR: {at['r_keys']} target keys, up to {at['n_att']} traces each. Majority = accuracy of always guessing the most frequent class. "
             rf"No-information reference (guess by prior): GE $\approx$ 1.2, SR $\approx$ 0.33. SR has a standard error of up to 0.05 (100 target keys). "
             rf"Models with near-100\% training accuracy (MLP) are overconfident, so a GE above the reference reflects miscalibration, not protection.}}")
    L.append(rf"\label{{tab:attack_s{str(s).replace('.', '')}}}")
    L.append(r"\begin{tabular}{llrrrrrrr}\toprule")
    L.append(rf"Config. & Attack & Top-1 (\%) & 95\% CI & Majority (\%) & GE@{at['n_att']} & SR@{at['n_att']} & Traces SR$\geq$0.5 & Traces SR$\geq$0.9\\\midrule")
    last = None
    for m, r, e in attack_rows(s):
        gt = r"$>$" + str(at["n_att"])
        n90 = r["traces_for_sr90"] if r["traces_for_sr90"] is not None else gt
        n50 = r["traces_for_sr50"] if r["traces_for_sr50"] is not None else gt
        cfg = NAME[m] if m != last else ""
        last = m
        L.append(rf"{cfg} & {ARCH[r['arch']]} & {100 * r['top1']:.1f} & {100 * r['top1_ci95'][0]:.1f}--{100 * r['top1_ci95'][1]:.1f} & "
                 rf"{100 * r['majority_baseline']:.1f} & {r['ge_at_nmax']:.2f} & {r['sr_at_nmax']:.2f} & {n50} & {n90}\\")
    L.append(r"\bottomrule\end{tabular}\end{table}")

LA = L[:]; L = []
# share diagnostic (CNN version, kept only in tables.tex)
if at["share_diag"]:
    L.append(r"\begin{table}[t]\centering")
    L.append(r"\caption{Mask-aware profiling diagnostic: accuracy of a CNN trained with known masks to predict $\mathrm{HW}$ of share $s_0$ of coefficient 0 (test set, random keys and masks).}")
    L.append(r"\label{tab:sharediag}\begin{tabular}{llrrr}\toprule")
    L.append(r"Config. & $\sigma$ & Top-1 (\%) & 95\% CI & Majority (\%)\\\midrule")
    for d in at["share_diag"]:
        L.append(rf"{NAME[d['mode']]} & {d['sigma']} & {100 * d['share0_top1']:.1f} & {100 * d['ci95'][0]:.1f}--{100 * d['ci95'][1]:.1f} & {100 * d['majority_baseline']:.1f}\\")
    L.append(r"\bottomrule\end{tabular}\end{table}")

LSH = L[:]; L = []
# SNR/NICV
L.append(r"\begin{table}[t]\centering\caption{Peak SNR and NICV of the target label $\mathrm{HW}(s[0][0])$ over all trace samples (profiling set).}\label{tab:snr}")
L.append(r"\begin{tabular}{lrrrr}\toprule Config. & $\sigma$ & Peak sample & Peak SNR & Peak NICV\\\midrule")
for key, e in at["results"].items():
    m, s = key.split("@")
    L.append(rf"{NAME[m]} & {s} & {e['snr_argmax']} & {e['snr_peak']:.4f} & {e['nicv_peak']:.4f}\\")
L.append(r"\bottomrule\end{tabular}\end{table}")
LS = L[:]
for _name, _blk in (("tables_tvla.tex", LT), ("tables_attacks.tex", LA), ("tables_snr.tex", LS)):
    open(os.path.join(R, _name), "w").write("\n".join(_blk) + "\n")
open(os.path.join(R, "tables.tex"), "w").write("\n".join(LT + LA + LSH + LS) + "\n")

# ---------------- GE / SR figure ----------------
for s in sorted({p[0] for p in at["plan"]}, reverse=True):
    fig, ax = plt.subplots(2, 3, figsize=(11, 5), sharex=True)
    for j, m in enumerate(MODES):
        for r in at["results"][f"{m}@{s}"]["models"]:
            a = r["arch"]
            ax[0, j].plot(range(1, len(cv[f"ge_{m}_{s}_{a}"]) + 1), cv[f"ge_{m}_{s}_{a}"], label=ARCH[a])
            ax[1, j].plot(range(1, len(cv[f"sr_{m}_{s}_{a}"]) + 1), cv[f"sr_{m}_{s}_{a}"], label=ARCH[a])
        ax[0, j].axhline(PRIOR_GE, color="grey", ls=":", lw=1)
        ax[0, j].set_title(NAME[m], fontsize=9); ax[1, j].set_xlabel("number of attack traces")
        if j == 0: ax[0, j].set_ylabel("guessing entropy (class rank)"); ax[1, j].set_ylabel("success rate")
        ax[0, j].set_ylim(0, 5.5); ax[1, j].set_ylim(0, 1.02)
    ax[0, 0].legend(fontsize=7)
    fig.suptitle(f"Rank / success vs traces, sigma={s} (dotted: no-information GE = prior-only)", fontsize=10)
    fig.tight_layout(); fig.savefig(os.path.join(R, f"fig_ge_sigma{s}.png"), dpi=160); plt.close(fig)
print("wrote tables.tex and figures")
