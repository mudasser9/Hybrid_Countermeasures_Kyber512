"""Second-order attack table + figure (measured values only)."""
import json, os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
so = json.load(open(os.path.join(R, "second_order.json")))["rows"]
cv = np.load(os.path.join(R, "second_order_curves.npz"))
VAR = ["C1", "C2 blind", "C2 oracle"]
DESC = {"C1": "C1, fixed sample pair", "C2 blind": "C2, fixed sample pair (blind)", "C2 oracle": "C2, location given (oracle)"}
r0 = so[0]
L = [r"% AUTO-GENERATED by make_report_so.py -- measured values only",
     r"\begin{table}[t]\centering",
     rf"\caption{{Second-order profiled template attack (LDA on the two share samples and their centred product). Profiling: {r0['n_train']} random-key traces; "
     rf"{r0['r_keys']} target keys, up to {r0['n_att']} traces each. ``Prior-only'' is the guessing entropy of an attacker who uses no trace.}}",
     r"\label{tab:second_order}\begin{tabular}{llrrrrr}\toprule",
     rf"$\sigma$ & Attacker & GE@{r0['n_att']} & SR@{r0['n_att']} & Traces SR$\geq$0.5 & Traces SR$\geq$0.9 & Prior-only GE\\\midrule"]
for s in sorted({r["sigma"] for r in so}):
    for v in VAR:
        r = next(x for x in so if x["sigma"] == s and x["variant"] == v)
        t50 = r["traces_sr50"] if r["traces_sr50"] else rf"$>${r['n_att']}"
        t90 = r["traces_sr90"] if r["traces_sr90"] else rf"$>${r['n_att']}"
        L.append(rf"{s} & {DESC[v]} & {r['ge_at_nmax']:.2f} & {r['sr_at_nmax']:.2f} & {t50} & {t90} & {r['prior_only_ge']:.2f}\\")
L.append(r"\bottomrule\end{tabular}\end{table}")
open(os.path.join(R, "tables_second_order.tex"), "w").write("\n".join(L) + "\n")

fig, ax = plt.subplots(1, 2, figsize=(10, 3.6), sharey=True)
for j, s in enumerate(sorted({r["sigma"] for r in so})):
    for v in VAR:
        sr = cv[f"sr_{v}_{s}"]
        ax[j].plot(range(1, len(sr) + 1), sr, label=DESC[v])
    ax[j].set_xscale("log"); ax[j].set_title(f"sigma = {s}", fontsize=9); ax[j].set_xlabel("number of attack traces")
    ax[j].axhline(0.33, color="grey", ls=":", lw=1)
ax[0].set_ylabel("success rate (rank 0)"); ax[0].legend(fontsize=7)
fig.suptitle("Second-order attack success vs traces (dotted: prior-only success = majority class)", fontsize=10)
fig.tight_layout(); fig.savefig(os.path.join(R, "fig_second_order.png"), dpi=160)
print("ok")
